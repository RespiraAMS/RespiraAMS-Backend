using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using Respira.Clinical.Application.Contracts.Data;
using Respira.Clinical.Application.Contracts.Mappers;
using Respira.Clinical.Domain.Entities;
using Respira.ServiceDefaults.Contracts.CQRS;
using Respira.ServiceDefaults.Contracts.Results;

namespace Respira.Clinical.Application.Features.ClinicalMetrics.UpdateRule
{
    public class UpdateRuleHandler(
        IDbContext context,
        IUpdateMapper<MetricRule, UpdateRuleCommand> mapper,
        ILogger<UpdateRuleHandler> logger)
        : ICommandHandler<UpdateRuleCommand, Result>
    {
        public async Task<Result> HandleAsync(UpdateRuleCommand command, CancellationToken cancellationToken = default)
        {
            // Get clinical metric by ID
            var metric = await context.ClinicalMetrics
                .Include(x => x.Rules)
                .ThenInclude(x => x.Criterion)
                .FirstOrDefaultAsync(x => x.Id == command.ClinicalMetricId, cancellationToken);
            if (metric is null)
            {
                logger.LogDebug("Clinical metric does not exist: {Id}", command.ClinicalMetricId);
                return Result.Failure(new Error(ApplicationStatus.BadRequest, "Clinical metric does not exist"));
            }

            // Check if the updated rule exists in metric
            var rule = metric.Rules.FirstOrDefault(x => x.Id == command.Id);
            if (rule is null)
            {
                logger.LogDebug("Rule {RuleID} does not exist in metric: {MetricID}", command.Id, command.ClinicalMetricId);
                return Result.Failure(new Error(ApplicationStatus.BadRequest, "Rule does not exist in metric"));
            }

            // Check if criterion exists
            if (await context.Criteria.FirstOrDefaultAsync(x => x.Id == command.CriterionId, cancellationToken) is null)
            {
                logger.LogDebug("Criterion does not exist: {Id}", command.CriterionId);
                return Result.Failure(new Error(ApplicationStatus.BadRequest, "Criterion does not exist"));
            }

            // Check if the pair (clinical metric, criterion) is unique
            if (metric.Rules.Any(x => x.Id != command.Id && x.CriterionId == command.CriterionId))
            {
                logger.LogDebug("There already exists a rule with this criterion {Id} in this metric", command.CriterionId);
                return Result.Failure(new Error(ApplicationStatus.BadRequest, "There already exists a rule with this criterion in this metric"));
            }

            // Because the rule type is generated by EF Core TPH, so we couldn't change
            // it value, so this update also won't allow update the type
            if ((rule is ScoringRule && command.ScoreFunction is null) || (rule is MajorMinorRule && command.IsMajor is null))
            {
                logger.LogDebug("Cannot update the type of rule: {detail}", new
                {
                    RuleId = command.Id,
                    DbType = rule.GetType().Name,
                    // The validator should ensure that score function and is major are mutually exclusive
                    CommandProvidedType = command.ScoreFunction is null ? typeof(ScoringRule).Name : typeof(MajorMinorRule).Name,
                });
                var msg = $"Cannot update rule: rule is {rule.GetType().Name}, so {(command.ScoreFunction is not null ? "ScoreFunction" : "IsMajor")} must be supplied";
                return Result.Failure(new Error(ApplicationStatus.BadRequest, msg));
            }

            // Map the command to model
            var variables = await context.ClinicalVariables.ToListAsync(cancellationToken);
            var mapResult = mapper.MapModel(rule, command, variables);
            if (mapResult.IsFailure())
            {
                logger.LogDebug("Failed to map command to model: {error}", mapResult.Error!);
                return Result.Failure(mapResult.Error!);
            }

            // Save changes to database
            await context.SaveChangesAsync(cancellationToken);
            return Result.Success(ApplicationStatus.Updated);

        }
    }
}
